//! 比較用 DTO の TypeScript 型が、コミット済みの `apps/desktop/src/generated/` と一致することを確認する。
//!
//! 検査対象は本 crate が所有する型名(`dto::OWNED_TYPE_NAMES`)のファイルだけ。共通 DTO(gui-api 由来)の
//! ファイルは gui-api 側の検査が所有するため対象外。更新手順:
//! `cargo run -p brainfuck-compare-api --example export_bindings`(生成物はコミットする)。
//! 型名の衝突検査: gui-api が書き出すファイル名と、本 crate が所有する型名が重ならないこと。

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};
use std::sync::atomic::{AtomicUsize, Ordering};
use std::time::{SystemTime, UNIX_EPOCH};

use brainfuck_compare_api::dto::{export_bindings, OWNED_TYPE_NAMES};
use ts_rs::Config;

/// テスト用の一時ディレクトリ(std のみ。Drop で削除する)。dev-dependency を増やさないための最小実装。
struct TempDir(PathBuf);

impl TempDir {
    fn new() -> Self {
        static COUNTER: AtomicUsize = AtomicUsize::new(0);
        let nanos = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .map(|d| d.as_nanos())
            .unwrap_or(0);
        let name = format!(
            "bf-compare-bindings-{}-{}-{}",
            std::process::id(),
            COUNTER.fetch_add(1, Ordering::Relaxed),
            nanos
        );
        let path = std::env::temp_dir().join(name);
        fs::create_dir_all(&path).expect("create temp dir");
        Self(path)
    }

    fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for TempDir {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

const COMMITTED_DIR: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../apps/desktop/src/generated"
);
const UPDATE_HINT: &str =
    "run `cargo run -p brainfuck-compare-api --example export_bindings` and commit the result";

fn read_ts_file(dir: &Path, name: &str) -> Option<String> {
    let path: PathBuf = dir.join(format!("{name}.ts"));
    // Windows の autocrlf で CRLF になっても内容は同一とみなす。
    fs::read_to_string(path)
        .ok()
        .map(|text| text.replace("\r\n", "\n"))
}

fn list_ts_names(dir: &Path) -> Vec<String> {
    let mut names: Vec<String> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("cannot read {}: {e}", dir.display()))
        .map(|entry| entry.expect("dir entry").path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "ts"))
        .map(|path| path.file_stem().unwrap().to_string_lossy().into_owned())
        .collect();
    names.sort();
    names
}

/// `owned` の各型名について、`fresh_dir` のファイルが `committed_dir` に同名で存在し内容が一致することを確認する。
/// 型名の一覧にない `committed_dir` 側のファイルは無視する。失敗時は `UPDATE_HINT` を含むメッセージを返す。
fn check_owned(fresh_dir: &Path, committed_dir: &Path, owned: &[&str]) -> Result<(), String> {
    let fresh: BTreeMap<&str, String> = owned
        .iter()
        .filter_map(|name| read_ts_file(fresh_dir, name).map(|text| (*name, text)))
        .collect();
    if fresh.is_empty() {
        return Err(format!("no bindings were generated; {UPDATE_HINT}"));
    }
    for name in owned {
        let Some(text) = fresh.get(name) else {
            return Err(format!(
                "{name}.ts was not generated by the export; {UPDATE_HINT}"
            ));
        };
        match read_ts_file(committed_dir, name) {
            None => {
                return Err(format!(
                    "{name}.ts is missing from the committed generated files; {UPDATE_HINT}"
                ))
            }
            Some(committed_text) if &committed_text != text => {
                return Err(format!(
                    "{name}.ts differs from the generated output; {UPDATE_HINT}"
                ))
            }
            Some(_) => {}
        }
    }
    Ok(())
}

/// テスト用の一時ディレクトリに `(ファイル名, 内容)` を書き出す。
fn write_files(dir: &Path, files: &[(&str, &str)]) {
    for (name, text) in files {
        fs::write(dir.join(name), text).expect("write test file");
    }
}

#[test]
fn owned_names_are_unique_and_non_empty() {
    assert!(!OWNED_TYPE_NAMES.is_empty());
    let mut sorted = OWNED_TYPE_NAMES.to_vec();
    sorted.sort_unstable();
    sorted.dedup();
    assert_eq!(
        sorted.len(),
        OWNED_TYPE_NAMES.len(),
        "owned type names must be unique"
    );
}

#[test]
fn owned_names_do_not_collide_with_gui_api_bindings() {
    // gui-api が書き出すファイル名と本 crate の型名が重なれば、後から書いた側が上書きしてしまう。
    let gui = TempDir::new();
    brainfuck_gui_api::dto::export_bindings(&Config::default().with_out_dir(gui.path()))
        .expect("export gui-api bindings");
    let gui_names = list_ts_names(gui.path());
    assert!(!gui_names.is_empty());
    for name in OWNED_TYPE_NAMES {
        assert!(
            !gui_names.iter().any(|g| g == name),
            "{name} collides with a gui-api generated type"
        );
    }
}

#[test]
fn unrelated_typescript_files_in_committed_dir_are_ignored() {
    let fresh = TempDir::new();
    let committed = TempDir::new();
    write_files(fresh.path(), &[("A.ts", "export type A = number;\n")]);
    write_files(
        committed.path(),
        &[
            ("A.ts", "export type A = number;\n"),
            ("ApiError.ts", "export type ApiError = string;\n"),
        ],
    );

    assert_eq!(check_owned(fresh.path(), committed.path(), &["A"]), Ok(()));
}

#[test]
fn hand_edited_generated_file_fails_with_update_hint() {
    let fresh = TempDir::new();
    let committed = TempDir::new();
    write_files(fresh.path(), &[("A.ts", "export type A = number;\n")]);
    write_files(committed.path(), &[("A.ts", "export type A = string;\n")]);

    let error = check_owned(fresh.path(), committed.path(), &["A"])
        .expect_err("an edited file must fail the check");
    assert!(
        error.contains("A.ts differs"),
        "unexpected message: {error}"
    );
    assert!(error.contains(UPDATE_HINT), "missing update hint: {error}");
}

#[test]
fn missing_generated_file_fails_with_update_hint() {
    let fresh = TempDir::new();
    let committed = TempDir::new();
    write_files(
        fresh.path(),
        &[
            ("A.ts", "export type A = number;\n"),
            ("B.ts", "export type B = number;\n"),
        ],
    );
    write_files(committed.path(), &[("A.ts", "export type A = number;\n")]);

    let error = check_owned(fresh.path(), committed.path(), &["A", "B"])
        .expect_err("a missing file must fail the check");
    assert!(
        error.contains("B.ts is missing"),
        "unexpected message: {error}"
    );
    assert!(error.contains(UPDATE_HINT), "missing update hint: {error}");
}

#[test]
fn committed_bindings_match_fresh_export() {
    let out = TempDir::new();
    let cfg = Config::default().with_out_dir(out.path());
    export_bindings(&cfg).expect("export bindings");

    if let Err(error) = check_owned(out.path(), Path::new(COMMITTED_DIR), OWNED_TYPE_NAMES) {
        panic!("{error}");
    }
}
